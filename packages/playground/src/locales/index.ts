function mergeInto(locale: 'zh-CN' | 'en-US', pg: Record<string, unknown>) {
  aiChatI18n.global.setLocaleMessage(locale, {
    ...aiChatI18n.global.getLocaleMessage(locale),
    pg,
  })
}
